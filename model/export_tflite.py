"""OPTIONAL (revision 2): put the classifier on the board itself.

  python -m model.export_tflite              # models/symbols_v1.tflite + firmware/model_data.h

Converts the Keras model to an int8 TensorFlow Lite model, calibrated on
synthetic crops, and writes it as a C array for TensorFlow Lite Micro. The
version 1 project does not need this: recognition runs on the laptop. It is
here for the "on-board recognition" idea after Dec 1. Expect about 150 KB of
model, which fits the Nano 33 BLE's 1 MB flash; segmentation and layout would
still have to be ported to C++.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import config
from model.data import load_npz
from pipeline.symbols import load_symbols


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default=config.MODEL_NAME)
    ap.add_argument("--calibration", type=Path, default=Path(config.SYNTH_DIR) / "train.npz")
    args = ap.parse_args(argv)

    import tensorflow as tf
    model = tf.keras.models.load_model(Path(config.MODELS_DIR) / f"{args.model}.keras")
    X, _ = load_npz(args.calibration, load_symbols())
    pick = np.random.default_rng(0).permutation(len(X))[:500]
    calib = (X[pick].astype(np.float32) / 255.0)[..., None]

    def representative():
        for i in range(len(calib)):
            yield [calib[i:i + 1]]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = representative
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    data = conv.convert()
    out = Path(config.MODELS_DIR) / f"{args.model}.tflite"
    out.write_bytes(data)
    header = Path(config.ROOT) / "firmware" / "model_data.h"
    body = ",".join(str(b) for b in data)
    header.write_text("// generated by model/export_tflite.py\n#pragma once\n"
                      f"alignas(16) const unsigned char g_model[] = {{{body}}};\n"
                      f"const unsigned int g_model_len = {len(data)};\n")
    print(f"{out} ({len(data) / 1024:.0f} KB) and {header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
